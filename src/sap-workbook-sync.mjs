import { cloneBook, PARTS_FIELDS, sheetValues } from './parts-workbook.mjs'
import { normalizedIdentity, applySapSnapshotReferences } from './sap-reference.mjs'
import { sapWorkbookDateScope, eligibleSapDate } from './parts-workbook-scope.mjs'

const lineKey = (po, item) => `${normalizedIdentity(po)}/${normalizedIdentity(item)}`
const openPoFacts = sap => ({eligible:sap?.OPEN_PO_ELIGIBLE === true,
  reason:sap?.OPEN_PO_REASON || (sap?.OPEN_PO_ELIGIBLE === true ? '' : 'open_status_unavailable'),
  openQty:sap?.OPEN_SCHEDULE_QTY ?? null, scheduleCount:sap?.OPEN_SCHEDULE_COUNT ?? null})
const mainSheet = book => book?.sheets.find(s => s.id === (book.mainSheetId || 's0'))
const fieldPositions = (book, sheet) => Object.fromEntries(PARTS_FIELDS.map((field, c) => [field,
  sheet.columns.findIndex(col => col.id === (book.importId ? sheet.fieldColumns?.[field] : `s0-c${c}`))]))

// Migrate only provably untouched rows generated by the old NG default.
// Existing human changes, including comments and completed statuses, win.
export function migrateSapPending(book, rows) {
  if (!book || book.sapStatusVersion === 1) return book
  const next = cloneBook(book), sheet = mainSheet(next)
  if (!sheet?.rows) return book
  const columns = fieldPositions(next, sheet), byLine = new Map(rows.map(s => [lineKey(s.EBELN, s.EBELP), s]))
  const generated = new Set(['seq','po','line','material','description_en','qty','ordered','completion'].map(f => columns[f]))
  for (const row of sheet.rows.slice(sheet.headerRows).filter(r => r.sapOrigin && r.sapPending === undefined)) {
    const sap = byLine.get(lineKey(row.sapAnchor?.po, row.sapAnchor?.item))
    const same = (a,b) => String(a ?? '') === String(b ?? '')
    const untouched = sap && !Object.keys(row.formulas || {}).length &&
      ['','NG'].includes(String(row.cells[columns.completion] ?? '').trim().toUpperCase()) &&
      row.cells.every((v,c) => generated.has(c) || v == null || v === '') &&
      [['po',sap.EBELN],['line',sap.EBELP],['material',sap.MATNR],['qty',sap.MENGE],['description_en',sap.TXZ01],['ordered',sap.BEDAT]].every(([f,v])=>columns[f]<0||same(row.cells[columns[f]],v))
    row.sapPending = !!untouched
    if (untouched && columns.completion >= 0) row.cells[columns.completion] = null
  }
  next.sapStatusVersion = 1
  return next
}

// Import the new China workbook verbatim, then carry only SAP-origin rows that
// it still does not represent. A matching China row always supplies its status.
export function retainSapWorkbookRows(replacement, previous) {
  const oldSheet = mainSheet(previous), target = mainSheet(replacement)
  if (!oldSheet?.rows?.some(r => r.sapOrigin) || !target?.rows) return replacement
  const next = cloneBook(replacement), sheet = mainSheet(next)
  const oldColumns = fieldPositions(previous, oldSheet), columns = fieldPositions(next, sheet)
  if (['po','line','material','qty'].some(f=>columns[f]<0)) throw new Error('invalid_import_mapping')
  const oldValues = sheetValues(oldSheet), values = sheetValues(sheet)
  const candidates = new Map()
  for (const row of oldSheet.rows.slice(oldSheet.headerRows)) {
    if (!row.sapAnchor) continue
    const key = lineKey(row.sapAnchor.po,row.sapAnchor.item)
    if (!candidates.has(key)) candidates.set(key,{EBELN:row.sapAnchor.po,EBELP:row.sapAnchor.item,MATNR:row.cells[oldColumns.material],MENGE:row.cells[oldColumns.qty]})
  }
  const orders = sheet.rows.slice(sheet.headerRows).map((row,i)=>({imported:true,workbookRowId:row.id,
    importFields:Object.fromEntries(['po','line','material','qty'].map(f=>[f,values[i+sheet.headerRows][columns[f]]]))}))
  applySapSnapshotReferences({orders},[...candidates.values()],Date.now())
  const represented = new Set(orders.filter(o=>o.sapAnchor).map(o=>lineKey(o.sapAnchor.po,o.sapAnchor.item)))
  for (const order of orders) {
    const f = order.importFields
    represented.add(lineKey(f.po,f.line))
  }
  const ids = new Set(sheet.rows.map(r=>r.id))
  const oldFields = new Map(Object.entries(oldColumns).map(([field,c])=>[c,field]))
  for (let r=oldSheet.headerRows;r<oldSheet.rows.length;r++) {
    const row = oldSheet.rows[r]
    if (!row.sapOrigin) continue
    const key = lineKey(row.sapAnchor?.po ?? row.cells[oldColumns.po],row.sapAnchor?.item ?? row.cells[oldColumns.line])
    if (represented.has(key)) continue
    const retained = cloneBook(row)
    retained.workbookOrderId ||= `PARTS-${previous.importId ? previous.importId+'-' : ''}${row.id}`
    if (ids.has(retained.id)) retained.id = `retained-${crypto.randomUUID()}`
    retained.cells = sheet.columns.map(()=>null); retained.formulas = {}; retained.types = {}; retained.fills = {}
    for (let c=0;c<oldSheet.columns.length;c++) {
      const destination = columns[oldFields.get(c)]
      if (destination == null || destination < 0) continue
      // Cross-import row references cannot safely be reused; retain their value.
      retained.cells[destination] = oldValues[r][c]
      if (row.types?.[c]) retained.types[destination] = row.types[c]
      if (row.fills?.[oldSheet.columns[c].id]) retained.fills[sheet.columns[destination].id] = row.fills[oldSheet.columns[c].id]
    }
    sheet.rows.push(retained);ids.add(retained.id);represented.add(key)
  }
  return next
}

// SAP supplies reference facts. Existing China workbook cells, formulas, status,
// notes and formatting are never rewritten by a refresh.
export function mergeSapWorkbook(book, orders, rows, run) {
  if (!book || !run) return book
  book = migrateSapPending(book, rows)
  const scope = sapWorkbookDateScope(book)
  if (book.sapRefreshRun === run && book.sapDateScopeVersion === 2 && book.sapOpenPoVersion === 1 && book.sapDateCutoff === scope.cutoff) return book
  const next = cloneBook(book), sheet = next.sheets.find(s => s.id === (next.mainSheetId || 's0'))
  if (!sheet) return book
  const columns = Object.fromEntries(PARTS_FIELDS.map((field, c) => [field,
    sheet.columns.findIndex(col => col.id === (book.importId ? sheet.fieldColumns?.[field] : `s0-c${c}`))]))
  if (['po', 'line', 'material', 'qty'].some(field => columns[field] < 0)) return book
  const byRow = new Map(orders.map(o => [o.workbookRowId, o])), represented = new Set()
  const sapByLine = new Map(rows.map(sap => [lineKey(sap.EBELN,sap.EBELP),sap]))
  for (const row of sheet.rows.slice(sheet.headerRows)) {
    const order = byRow.get(row.id)
    const anchor = row.sapAnchor || order?.sapAnchor
    if (row.sapOrigin) row.sapOpenPo = openPoFacts(sapByLine.get(lineKey(anchor?.po ?? row.cells[columns.po],anchor?.item ?? row.cells[columns.line])))
    if (anchor) {
      represented.add(lineKey(anchor.po, anchor.item))
      row.sapAnchor = cloneBook(anchor)
      row.sapLineConvention ||= order?.sapLineConvention || 'sap'
    }
    // An edited anchored PO remains linked to its original SAP line.
    if (!anchor) represented.add(lineKey(row.cells[columns.po], row.cells[columns.line]))
  }
  // Ambiguous links remain review items; do not inflate the workbook by adding
  // every possible SAP candidate as a supposedly new order.
  for (const order of orders.filter(o => o.sapReferenceReason === 'ambiguous')) {
    for (const sap of rows) if (normalizedIdentity(sap.EBELN) === normalizedIdentity(order.po) &&
      String(sap.MATNR) === String(order.part) && sap.MENGE === order.qty) represented.add(lineKey(sap.EBELN, sap.EBELP))
  }
  const existingIds = new Set(sheet.rows.map(row => row.id))
  let sequence = Math.max(0, ...sheet.rows.slice(sheet.headerRows).map(r => Number(r.cells[columns.seq]) || 0))
  for (const sap of rows) {
    if (!eligibleSapDate(sap.BEDAT, scope.cutoff)) continue
    if (sap.OPEN_PO_ELIGIBLE !== true) continue
    const key = lineKey(sap.EBELN, sap.EBELP)
    if (represented.has(key)) continue
    const id = `sap-${normalizedIdentity(sap.EBELN)}-${normalizedIdentity(sap.EBELP)}`
    // A deleted/replaced source is never silently overwritten by a generated ID.
    if (existingIds.has(id)) continue
    const fields = {seq: ++sequence, po: sap.EBELN, line: sap.EBELP, material: sap.MATNR,
      description_en: sap.TXZ01 || '', qty: sap.MENGE, ordered: sap.BEDAT || '',
      completion: null}
    const cells = sheet.columns.map(() => null)
    for (const [field, value] of Object.entries(fields)) if (columns[field] >= 0) cells[columns[field]] = value
    sheet.rows.push({id, cells, formulas: {}, types: {}, sapOrigin: true, sapPending: true, sapNewRun: run, sapOpenPo:openPoFacts(sap),
      sapAnchor: {po: String(sap.EBELN), item: String(sap.EBELP)}, sapLineConvention: 'sap',
      importKey: JSON.stringify([String(sap.EBELN), String(sap.EBELP), String(sap.MATNR || '')])})
    represented.add(key)
  }
  next.sapRefreshRun = run
  next.sapDateScopeVersion = 2
  next.sapOpenPoVersion = 1
  next.sapDateCutoff = scope.cutoff
  return next
}
